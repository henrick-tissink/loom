package discipline

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"io/fs"
	"path"
	"sort"
	"strings"
)

// ManifestFile is one bundle file: where it sits in the bundle, what it
// hashes to, the mode it is installed with, and where it is installed.
// Target "rev" means inside the immutable per-revision directory; anything
// else is an absolute location with "~" for the home directory.
type ManifestFile struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
	Mode   string `json:"mode"`
	Target string `json:"target"`
}

// Manifest is bundle/manifest.json: generated by `go generate`, committed,
// and pinned by TestManifestCurrent so a bundle edit cannot ship without a
// regenerated manifest.
type Manifest struct {
	Rev              string         `json:"rev"`
	ClaudeCodeTested []string       `json:"claudeCodeTested"`
	Files            []ManifestFile `json:"files"`
	Registrations    string         `json:"registrations"`
	// History maps an earlier revision (or a named snapshot such as the
	// seed copied from the owner's machine) to that revision's file hashes.
	// A file that matches one of these is "stale": known, and safe to
	// replace. One that matches nothing is "modified": the user's.
	History map[string]map[string]string `json:"history"`
}

// Registration is one hook registration as settings.json expects it,
// with the script relative to the bundle.
type Registration struct {
	Event     string `json:"event"`
	Matcher   string `json:"matcher"`
	Script    string `json:"script"`
	Timeout   int    `json:"timeout"`
	OnFailure string `json:"onFailure,omitempty"`
}

// Registrations is bundle/registrations.json: everything the bundle asks
// settings.json to carry. "<ccd>" in a value stands for the Claude config
// directory.
type Registrations struct {
	Hooks      []Registration `json:"hooks"`
	StatusLine struct {
		Type    string `json:"type"`
		Command string `json:"command"`
	} `json:"statusLine"`
	Env             map[string]string `json:"env"`
	PermissionsDeny []string          `json:"permissionsDeny"`
}

const (
	manifestName      = "manifest.json"
	registrationsName = "registrations.json"
	revName           = "REV"
	rulesName         = "CLAUDE.how-to-work.md"
	deadlineTarget    = "~/.local/bin/deadline"
	// ImportLine is the one line CLAUDE.md carries once the bundle is
	// installed in the revision layout (phase 2); the doctor reports it.
	ImportLine = "@discipline/current/" + rulesName
)

// LoadManifest reads the embedded manifest.
func LoadManifest() (Manifest, error) {
	return readManifest(Bundle())
}

func readManifest(fsys fs.FS) (Manifest, error) {
	var m Manifest
	b, err := fs.ReadFile(fsys, manifestName)
	if err != nil {
		return m, err
	}
	if err := json.Unmarshal(b, &m); err != nil {
		return m, fmt.Errorf("%s: %w", manifestName, err)
	}
	return m, nil
}

// LoadRegistrations reads the embedded registrations file.
func LoadRegistrations() (Registrations, error) {
	var r Registrations
	b, err := fs.ReadFile(Bundle(), registrationsName)
	if err != nil {
		return r, err
	}
	if err := json.Unmarshal(b, &r); err != nil {
		return r, fmt.Errorf("%s: %w", registrationsName, err)
	}
	return r, nil
}

// BundledRev is the revision the embedded bundle declares (its REV file).
func BundledRev() string {
	b, err := fs.ReadFile(Bundle(), revName)
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(b))
}

// ComputeFiles walks a bundle and returns its manifest entries, sorted by
// path. The manifest itself is left out (it cannot contain its own hash).
func ComputeFiles(fsys fs.FS) ([]ManifestFile, error) {
	var out []ManifestFile
	err := fs.WalkDir(fsys, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name := d.Name()
		if d.IsDir() {
			if p != "." && (strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_")) {
				return fs.SkipDir
			}
			return nil
		}
		if p == manifestName || strings.HasPrefix(name, ".") || strings.HasSuffix(name, ".pyc") {
			return nil
		}
		f, err := fsys.Open(p)
		if err != nil {
			return err
		}
		defer f.Close()
		h := sha256.New()
		if _, err := io.Copy(h, f); err != nil {
			return err
		}
		out = append(out, ManifestFile{
			Path:   p,
			SHA256: hex.EncodeToString(h.Sum(nil)),
			Mode:   fileMode(p),
			Target: fileTarget(p),
		})
		return nil
	})
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, err
}

// fileMode is the mode a bundle file is installed with: scripts and the
// deadline wrapper executable, everything else plain.
func fileMode(p string) string {
	switch {
	case strings.HasPrefix(p, "tests/") && strings.HasSuffix(p, ".py"):
		return "0644" // suites are run as `python3 -I file`, never executed directly
	case strings.HasPrefix(p, "bin/"), strings.HasSuffix(p, ".py"), strings.HasSuffix(p, ".sh"):
		return "0755"
	}
	return "0644"
}

func fileTarget(p string) string {
	if p == "bin/deadline" {
		return deadlineTarget
	}
	return "rev"
}

// Dir is the bundle directory a path belongs to ("enforce", "tests", …),
// or "" for a top-level file.
func Dir(p string) string {
	d := path.Dir(p)
	if d == "." {
		return ""
	}
	return d
}
